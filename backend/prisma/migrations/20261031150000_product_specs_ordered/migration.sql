-- Характеристики товара: объект → массив пар [{ "key", "value" }, …].
--
-- В jsonb ключи объекта не хранят порядок вставки: Postgres сортирует их
-- (сначала по длине, затем побайтно), поэтому порядок, который редактор задал
-- в админке, терялся — «Объём, Материал, Давление» возвращались как
-- «Объём, Давление, Материал». Порядок элементов массива jsonb сохраняет.
--
-- Исходный порядок уже существующих характеристик восстановить нельзя:
-- переносим их в том порядке, в каком их хранит jsonb. Тип столбца не
-- меняется (jsonb), меняется только форма значения.

UPDATE "Product"
SET specs = (
  SELECT COALESCE(
    jsonb_agg(jsonb_build_object('key', e.key, 'value', e.value) ORDER BY e.n),
    '[]'::jsonb
  )
  FROM jsonb_each_text(specs) WITH ORDINALITY AS e(key, value, n)
)
WHERE jsonb_typeof(specs) = 'object';
