-- Номера заявок — к виду с кодом страны (common/phone/phone.ts).
--
-- «+7» рядом с полем формы было подписью и в значение не попадало: заявки
-- с «(707) 267-12-37» сохранялись как phoneDigits = 7072671237. Ссылка
-- tel:+7072671237 в админке звонила не туда, а поиск не склеивал такие
-- заявки с «+7 707…». Чиним то, что уже успело сохраниться.

-- 1. 10 цифр — номер без кода страны: рядом с полем стояло «+7».
UPDATE "Lead"
SET "phoneDigits" = '7' || "phoneDigits"
WHERE "phoneDigits" ~ '^[0-9]{10}$';

-- 2. 11 цифр с ведущей 8 — междугородний набор. Только если номер набран
--    без «+»: «+8…» — это код другой страны (+81, +86…), его не трогаем.
UPDATE "Lead"
SET "phoneDigits" = '7' || substr("phoneDigits", 2)
WHERE "phoneDigits" ~ '^8[0-9]{10}$'
  AND btrim(phone) NOT LIKE '+%';

-- 3. Номера +7 — в единый вид, как их теперь сохраняет бэкенд. Исходная
--    запись посетителя ничего не добавляет: цифры те же, а разнобой мешает
--    менеджеру сверять дубли глазами.
UPDATE "Lead"
SET phone = '+7 (' || substr("phoneDigits", 2, 3) || ') '
  || substr("phoneDigits", 5, 3) || '-'
  || substr("phoneDigits", 8, 2) || '-'
  || substr("phoneDigits", 10, 2)
WHERE "phoneDigits" ~ '^7[0-9]{10}$';
