import { normalizePhone, phoneSearchDigits } from './phone.js';

describe('normalizePhone', () => {
  it.each([
    // Как вводят в поле рядом с нарисованным «+7».
    ['(707) 267-12-37', '77072671237'],
    ['7072671237', '77072671237'],
    // Привычные полные записи.
    ['+7 (707) 267-12-37', '77072671237'],
    ['+77072671237', '77072671237'],
    ['8 707 267 12 37', '77072671237'],
    ['87072671237', '77072671237'],
    ['7 707 267 12 37', '77072671237'],
  ])('«%s» → %s', (input, digits) => {
    expect(normalizePhone(input)).toEqual({ digits, display: '+7 (707) 267-12-37' });
  });

  it('иностранный номер с плюсом сохраняется как есть', () => {
    expect(normalizePhone('+998 90 123 45 67')).toEqual({
      digits: '998901234567',
      display: '+998901234567',
    });
  });

  it('ведущая 8 после плюса — код страны, а не междугородний набор', () => {
    // +81 — Япония: 8 здесь не превращается в 7.
    expect(normalizePhone('+81 3 1234 5678')?.digits).toBe('81312345678');
  });

  it.each([
    ['', 'пусто'],
    ['123', 'слишком коротко'],
    ['707 267 12', 'не хватает цифр'],
    ['9 707 267 12 37', '11 цифр, но не с 7 и не с 8'],
    ['+7 707 267 12 3', '+7 и 9 цифр'],
    ['+7 707 267 12 37 1', '+7 и 11 цифр'],
    ['+1234567', 'короче E.164'],
  ])('«%s» отвергается: %s', (input) => {
    expect(normalizePhone(input)).toBeNull();
  });
});

describe('phoneSearchDigits', () => {
  it('8 в начале полного номера сводится к 7', () => {
    expect(phoneSearchDigits('8 707 267 12 37')).toBe('77072671237');
  });

  it('часть номера остаётся как есть — поиск по вхождению', () => {
    expect(phoneSearchDigits('267-12')).toBe('26712');
    expect(phoneSearchDigits('(707) 267-12-37')).toBe('7072671237');
  });
});
