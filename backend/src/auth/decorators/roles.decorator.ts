import { SetMetadata } from '@nestjs/common';
import type { AdminRole } from '../../prisma/client.js';

export const ROLES_KEY = 'roles';

/**
 * Без декоратора эндпоинт доступен любому вошедшему администратору.
 *
 * Кто что может:
 *   EDITOR — заявки (статус, заметка, ответственный); товары и категории:
 *            создать, править, публиковать, переставлять; загрузка картинок
 *            и подписи к ним; подключение своего Telegram.
 *   OWNER  — всё то же плюс необратимое и структурное: удаление товаров,
 *            категорий и картинок, значения фильтров, бот Telegram и чужие
 *            чаты, учётные записи администраторов, журнал действий.
 *
 * Правило для новых эндпоинтов: удаление и то, что меняет устройство
 * каталога или доступ, — @Roles(AdminRole.OWNER).
 */
export const Roles = (...roles: AdminRole[]) => SetMetadata(ROLES_KEY, roles);
